def _series_rgba(hex_color, alpha):
    """'#2a78d6', 0.15 → 'rgba(42,120,214,0.15)' — заливка под линией."""
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r},{g},{b},{alpha})"
